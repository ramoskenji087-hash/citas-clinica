-- Migración: activación de cuentas y recuperación de contraseña por correo.
--
-- Ejecutar UNA sola vez sobre la base citas_clinica (en pgAdmin, Query Tool).
-- No hace falta para la base de pruebas: se recrea desde schema.sql, que ya incluye esta tabla.

CREATE TABLE IF NOT EXISTS token_usuario (
    id_token       INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario     INTEGER      NOT NULL REFERENCES usuario (id_usuario),
    tipo           VARCHAR(20)  NOT NULL CHECK (tipo IN ('activacion', 'recuperacion')),
    token_hash     CHAR(64)     NOT NULL UNIQUE,   -- SHA-256 del token; el token en claro solo viaja en el correo
    expira         TIMESTAMP    NOT NULL,
    usado          BOOLEAN      NOT NULL DEFAULT FALSE,
    fecha_creacion TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_token_usuario_usuario ON token_usuario (id_usuario, tipo);
