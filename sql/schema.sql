-- =============================================================================
-- sql/schema.sql
-- Sistema Web de Gestión de Citas Médicas - Clínica Vida Salud
-- Motor: PostgreSQL 13 o superior. Archivo guardado en UTF-8.
--
-- ADVERTENCIA: este script BORRA y vuelve a crear las tablas del proyecto.
-- Ejecutarlo solo en una base de datos de desarrollo o de pruebas.
--
-- Qué garantiza la base de datos y qué debe validar PHP:
--   BD  : unicidad (CI, códigos, nombre de usuario, especialidad normalizada),
--         claves foráneas, rangos y valores válidos (CHECK), estados permitidos
--         y la restricción EXCLUDE que impide citas superpuestas (RF07, RN07, RN09).
--   PHP : reglas que dependen de la hora actual o de la lógica de negocio:
--         no fechas pasadas (RN06), médico activo (RN04), cita dentro del horario
--         (RN05), duración (RN08), máquina de estados (RF10), permisos (RN12),
--         y la comprobación con SELECT ... FOR UPDATE (RN13).
--
-- Convenciones:
--   * Claves: INTEGER GENERATED BY DEFAULT AS IDENTITY.
--   * Códigos legibles (PAC-0001, MED-0001, CM-0001): columnas generadas a partir
--     del id. PHP no tiene que calcularlos.
--   * Ninguna clave foránea usa ON DELETE CASCADE. La aplicación nunca borra
--     pacientes, médicos ni especialidades: los desactiva (RN11).
--   * dia_semana sigue la numeración ISO: 1 = lunes ... 7 = domingo
--     (la misma que date('N') en PHP y EXTRACT(ISODOW) en PostgreSQL).
--   * Fechas y horas sin zona horaria (TIMESTAMP). PHP y PostgreSQL deben
--     usar la misma zona horaria.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 0. Limpieza: permite volver a ejecutar el script sin errores.
-- -----------------------------------------------------------------------------
DROP TABLE IF EXISTS cita                CASCADE;
DROP TABLE IF EXISTS usuario             CASCADE;
DROP TABLE IF EXISTS horario_medico      CASCADE;
DROP TABLE IF EXISTS medico_especialidad CASCADE;
DROP TABLE IF EXISTS especialidad        CASCADE;
DROP TABLE IF EXISTS medico              CASCADE;
DROP TABLE IF EXISTS paciente            CASCADE;
DROP TABLE IF EXISTS rol                 CASCADE;

-- Extensión necesaria para usar el operador "=" sobre enteros dentro de un
-- índice GiST, que a su vez se usa en la restricción EXCLUDE de la tabla cita.
-- Desde PostgreSQL 13 es una extensión "trusted": el dueño de la base puede crearla.
CREATE EXTENSION IF NOT EXISTS btree_gist;

-- -----------------------------------------------------------------------------
-- 1. ROL (catálogo fijo). Los id son fijos para que las restricciones puedan
--    referirse a ellos: 1 = Administrador, 2 = Recepcionista, 3 = Médico, 4 = Paciente.
-- -----------------------------------------------------------------------------
CREATE TABLE rol (
    id_rol  SMALLINT     PRIMARY KEY,
    nombre  VARCHAR(30)  NOT NULL UNIQUE
);

-- -----------------------------------------------------------------------------
-- 2. PACIENTE (RF02, RN01, RN11)
--    La CI es el identificador de negocio: única y obligatoria.
--    Se desactiva con "activo"; nunca se borra si tiene citas.
-- -----------------------------------------------------------------------------
CREATE TABLE paciente (
    id_paciente      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo           VARCHAR(12) GENERATED ALWAYS AS ('PAC-' || LPAD(id_paciente::text, 4, '0')) STORED UNIQUE,
    ci               VARCHAR(15) NOT NULL UNIQUE
                     CHECK (ci ~ '^[A-Za-z0-9-]{5,15}$'),
    nombres          VARCHAR(80) NOT NULL CHECK (char_length(nombres) BETWEEN 2 AND 80),
    apellidos        VARCHAR(80) NOT NULL CHECK (char_length(apellidos) BETWEEN 2 AND 80),
    fecha_nacimiento DATE        NOT NULL CHECK (fecha_nacimiento <= CURRENT_DATE),
    sexo             VARCHAR(10) NOT NULL CHECK (sexo IN ('Masculino', 'Femenino', 'Otro')),
    telefono         VARCHAR(16) NOT NULL CHECK (telefono ~ '^\+?[0-9]{7,15}$'),
    correo           VARCHAR(120) NULL
                     CHECK (correo IS NULL OR correo ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
    direccion        VARCHAR(200) NULL,
    activo           BOOLEAN     NOT NULL DEFAULT TRUE,
    fecha_registro   TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- -----------------------------------------------------------------------------
-- 3. MÉDICO (RF03, RN02, RN11)
--    El número de registro profesional es único. Se desactiva con "activo".
-- -----------------------------------------------------------------------------
CREATE TABLE medico (
    id_medico            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo               VARCHAR(12) GENERATED ALWAYS AS ('MED-' || LPAD(id_medico::text, 4, '0')) STORED UNIQUE,
    registro_profesional VARCHAR(30) NOT NULL UNIQUE,
    nombres              VARCHAR(80) NOT NULL CHECK (char_length(nombres) BETWEEN 2 AND 80),
    apellidos            VARCHAR(80) NOT NULL CHECK (char_length(apellidos) BETWEEN 2 AND 80),
    telefono             VARCHAR(16) NOT NULL CHECK (telefono ~ '^\+?[0-9]{7,15}$'),
    correo               VARCHAR(120) NOT NULL
                         CHECK (correo ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
    activo               BOOLEAN     NOT NULL DEFAULT TRUE
);

-- -----------------------------------------------------------------------------
-- 4. ESPECIALIDAD (RF04)
--    Dos especialidades no pueden tener el mismo nombre normalizado.
-- -----------------------------------------------------------------------------
CREATE TABLE especialidad (
    id_especialidad INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(80)  NOT NULL CHECK (btrim(nombre) <> ''),
    descripcion     VARCHAR(255) NULL,
    activo          BOOLEAN      NOT NULL DEFAULT TRUE
);

-- Índice único sobre el nombre normalizado: sin tildes, en minúsculas y con los
-- espacios repetidos reducidos a uno. PHP debe aplicar EXACTAMENTE la misma
-- transformación (mismo mapa de tildes) antes de comparar o guardar.
CREATE UNIQUE INDEX ux_especialidad_nombre_normalizado
    ON especialidad (
        btrim(regexp_replace(
            lower(translate(nombre, 'ÁÉÍÓÚÜÑáéíóúüñ', 'AEIOUUNaeiouun')),
            '\s+', ' ', 'g'
        ))
    );

-- -----------------------------------------------------------------------------
-- 5. MÉDICO_ESPECIALIDAD (relación N:M: un médico puede tener varias
--    especialidades y una especialidad puede tener varios médicos).
-- -----------------------------------------------------------------------------
CREATE TABLE medico_especialidad (
    id_medico       INTEGER NOT NULL REFERENCES medico (id_medico),
    id_especialidad INTEGER NOT NULL REFERENCES especialidad (id_especialidad),
    PRIMARY KEY (id_medico, id_especialidad)
);

CREATE INDEX ix_medico_especialidad_especialidad
    ON medico_especialidad (id_especialidad);

-- -----------------------------------------------------------------------------
-- 6. HORARIO_MEDICO (RF05, RN05, RN08)
--    Un bloque de atención por fila. Ejemplo: lunes de 08:00 a 12:00 con citas
--    de 30 minutos. Los solapes entre bloques del mismo médico y día se
--    validan en PHP (ver pregunta pendiente en el análisis).
-- -----------------------------------------------------------------------------
CREATE TABLE horario_medico (
    id_horario    INTEGER  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_medico     INTEGER  NOT NULL REFERENCES medico (id_medico),
    dia_semana    SMALLINT NOT NULL CHECK (dia_semana BETWEEN 1 AND 7),
    hora_inicio   TIME     NOT NULL,
    hora_fin      TIME     NOT NULL,
    duracion_cita SMALLINT NOT NULL CHECK (duracion_cita IN (15, 20, 30, 45, 60)),
    CONSTRAINT ck_horario_rango CHECK (hora_fin > hora_inicio)
);

CREATE INDEX ix_horario_medico_dia ON horario_medico (id_medico, dia_semana);

-- -----------------------------------------------------------------------------
-- 7. USUARIO (RF01, RN12)
--    Cada usuario tiene un rol. Si el rol es Médico (3), debe estar vinculado
--    a un registro de médico. "puede_marcar_atendida" es el permiso que la
--    sección 3.3 del documento describe para el médico ("si ese permiso le ha sido asignado").
-- -----------------------------------------------------------------------------
CREATE TABLE usuario (
    id_usuario            INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_usuario        VARCHAR(30)  NOT NULL UNIQUE,
    correo                VARCHAR(120) NOT NULL UNIQUE,
    nombres               VARCHAR(80)  NOT NULL,
    apellidos             VARCHAR(80)  NOT NULL,
    password_hash         VARCHAR(255) NOT NULL,           -- resultado de password_hash() en PHP
    id_rol                SMALLINT     NOT NULL REFERENCES rol (id_rol),
    id_medico             INTEGER      NULL UNIQUE REFERENCES medico (id_medico),
    id_paciente           INTEGER      NULL UNIQUE REFERENCES paciente (id_paciente),
    puede_marcar_atendida BOOLEAN      NOT NULL DEFAULT FALSE,
    activo                BOOLEAN      NOT NULL DEFAULT TRUE,
    -- Un usuario con rol Médico (3) debe estar vinculado a un médico.
    CONSTRAINT ck_usuario_medico_vinculado CHECK (id_rol <> 3 OR id_medico IS NOT NULL),
    -- Un usuario con rol Paciente (4) debe estar vinculado a una ficha de paciente.
    CONSTRAINT ck_usuario_paciente_vinculado CHECK (id_rol <> 4 OR id_paciente IS NOT NULL),
    -- Solo el rol Paciente puede tener vínculo con un paciente, y solo el rol Médico con un médico.
    CONSTRAINT ck_usuario_vinculo_paciente CHECK (id_paciente IS NULL OR id_rol = 4),
    CONSTRAINT ck_usuario_vinculo_medico CHECK (id_medico IS NULL OR id_rol = 3),
    -- Solo el rol Médico puede tener el permiso de marcar citas como atendidas.
    CONSTRAINT ck_usuario_permiso_atendida CHECK (puede_marcar_atendida = FALSE OR id_rol = 3)
);

-- Enlaces de un solo uso para activar una cuenta y para recuperar la contraseña (se envían por correo).
-- Se guarda solo el hash SHA-256 del token; el token en claro viaja únicamente en el correo.
CREATE TABLE token_usuario (
    id_token       INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario     INTEGER      NOT NULL REFERENCES usuario (id_usuario),
    tipo           VARCHAR(20)  NOT NULL CHECK (tipo IN ('activacion', 'recuperacion')),
    token_hash     CHAR(64)     NOT NULL UNIQUE,
    expira         TIMESTAMP    NOT NULL,
    usado          BOOLEAN      NOT NULL DEFAULT FALSE,
    fecha_creacion TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX ix_token_usuario_usuario ON token_usuario (id_usuario, tipo);

-- -----------------------------------------------------------------------------
-- 8. CITA (RF06 a RF10, RN03, RN07, RN09, RN10)
--    Estados que OCUPAN horario: Programada, Confirmada, Atendida, Inasistencia.
--    Estado que NO ocupa horario: Cancelada (RN09).
--    La cita conserva su registro siempre; no se borra (RF09).
-- -----------------------------------------------------------------------------
CREATE TABLE cita (
    id_cita             INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo              VARCHAR(12)  GENERATED ALWAYS AS ('CM-' || LPAD(id_cita::text, 4, '0')) STORED UNIQUE,
    id_paciente         INTEGER      NOT NULL REFERENCES paciente (id_paciente),
    id_medico           INTEGER      NOT NULL REFERENCES medico (id_medico),
    id_especialidad     INTEGER      NOT NULL REFERENCES especialidad (id_especialidad),
    inicio              TIMESTAMP    NOT NULL,
    fin                 TIMESTAMP    NOT NULL,
    motivo              VARCHAR(200) NULL,
    estado              VARCHAR(20)  NOT NULL DEFAULT 'Programada'
                        CHECK (estado IN ('Programada', 'Confirmada', 'Atendida', 'Cancelada', 'Inasistencia')),
    motivo_cancelacion  VARCHAR(255) NULL,
    fecha_creacion      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id_usuario_registro INTEGER      NOT NULL REFERENCES usuario (id_usuario),

    CONSTRAINT ck_cita_fin_posterior CHECK (fin > inicio),

    -- RF09: cancelar exige motivo.
    CONSTRAINT ck_cita_motivo_cancelacion
        CHECK (estado <> 'Cancelada' OR (motivo_cancelacion IS NOT NULL AND btrim(motivo_cancelacion) <> '')),

    -- La especialidad de la cita debe ser una que atiende ese médico.
    CONSTRAINT fk_cita_medico_especialidad
        FOREIGN KEY (id_medico, id_especialidad)
        REFERENCES medico_especialidad (id_medico, id_especialidad),

    -- RF07 / RN07 / RN09: un médico no puede tener dos citas que se solapen.
    -- Las canceladas quedan fuera de la restricción, así liberan el horario.
    -- Dos rangos [inicio, fin) son compatibles si uno termina justo cuando empieza el otro.
    CONSTRAINT ex_cita_medico_sin_solapes
        EXCLUDE USING gist (
            id_medico WITH =,
            tsrange(inicio, fin, '[)') WITH &&
        )
        WHERE (estado <> 'Cancelada')
);

-- Índices pedidos por el diseño: agenda por médico y fecha, historial por
-- paciente y filtros por estado.
CREATE INDEX ix_cita_medico_inicio ON cita (id_medico, inicio);
CREATE INDEX ix_cita_paciente      ON cita (id_paciente);
CREATE INDEX ix_cita_estado        ON cita (estado);

